function buildCss() {
  const root = postcss.parse(read('app.raw.css'));
  const ats = [];
  root.walkAtRules((at) => ats.push(at));
  for (const at of ats) {
    if (/keyframes$|^font-face$/.test(at.name)) at.remove();
    else if (at.name === 'media') {
      // The film shows the dark theme at desktop width, so those branches are made unconditional.
      if (/prefers-color-scheme:\s*dark|min-width:\s*700px/.test(at.params)) at.replaceWith(at.nodes);
      else at.remove();
    }
  }
  root.walkDecls((d) => {
    // The renderer seeks frame by frame: nothing may move on its own clock.
    if (/^(transition|animation)(-|$)|^will-change$|^scroll-behavior$/.test(d.prop) || /url\(/.test(d.value)) return void d.remove();
    d.value = d.value
      .replace(/(-?\d*\.?\d+)[dsl]?vh\b/g, (_, n) => +(n * 9).toFixed(2) + 'px')
      .replace(/(-?\d*\.?\d+)[dsl]?vw\b/g, (_, n) => +(n * 14.4).toFixed(2) + 'px');
  });
  root.walkRules((r) => {
    r.selectors = r.selectors.map((sel) => {
      const s = sel.replace(/:root:not\(\[data-theme=["']?light["']?\]\)/g, ':root').replace(/#root(?![\w-])/g, '.kv-root');
      if (/^(:root|html|body)(?![\w-])/.test(s)) return s.replace(/^(:root|html|body)/, '.kv-app').replace(/^\.kv-app\s+body(?![\w-])/, '.kv-app');
      return '.kv-app ' + s;
    });
  });
  const own = `
.kv-app { position: relative; width: 1440px; height: 900px; margin: 0; overflow: hidden; contain: layout paint; color-scheme: dark; text-align: left; }
.kv-app .kv-root { position: absolute; left: 0; top: 0; width: 1440px; height: 900px; }
.kv-app * { scrollbar-width: none; }
.kv-app .kv-mapimg { max-width: none; display: block; }
.kv-app input { caret-color: transparent; }
`;
  const css = '/* Naari Kavach app stylesheet, scoped for the film. Generated by tools/build-walkthrough.mjs. */\n' + root.toString() + own;
  fs.writeFileSync(PROJ + 'assets/app/kavach.css', css);
  return css.length;
}

// ---------------------------------------------------------------- snapshots
const uniq = (h, sfx) => h.replace(/\b(rtc\d|rtf)\b/g, '$1-' + sfx);
function snap(name, sfx, extra = '') {
  const h = read(name + '.html').replace('__MAP__', 'assets/app/map-' + name + '.png').replace(/<\/div>$/, extra + '</div>');
  return '<div class="kv-root">' + uniq(h, sfx) + '</div>';
}

// ---------------------------------------------------------------- camera: the app is 1440x900 inside a 1300x812.5 window
const W = 1300, H = 812.5, S0 = W / 1440;
function cam(cx, cy, z) {
  const s = S0 * z;
  const x = Math.min(0, Math.max(W - 1440 * s, W / 2 - cx * s));
  const y = Math.min(0, Math.max(H - 900 * s, H / 2 - cy * s));
  return JSON.stringify({ x: +x.toFixed(1), y: +y.toFixed(1), scale: +s.toFixed(4) });
}
